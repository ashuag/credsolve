#!/usr/bin/env node
/**
 * Bulk-import states (verify), cities (~1k), and pincodes (~20k) from generic CSV exports.
 *
 * Do NOT use prisma/seed for this — one row per upsert is too slow for prod.
 *
 * Usage:
 *   node scripts/import-geography-bulk.mjs --csv-dir "/path/to/city data"
 *   node scripts/import-geography-bulk.mjs --csv-dir "/path/to/city data" --sql-only
 *   node scripts/import-geography-bulk.mjs --csv-dir "/path/to/city data" --execute
 *
 * Prod (recommended):
 *   1. npm run prisma:migrate:deploy
 *   2. node scripts/import-geography-bulk.mjs --csv-dir "..." --sql-only
 *   3. mysql -h HOST -u USER -p DB < prisma/data/geography/generated/import_geography.sql
 *
 * Requires DATABASE_URL in env for --execute (uses mysql CLI when available, else Prisma).
 */
import { createReadStream, mkdirSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

const CSV_STATE = 'generic_state_202605291856.csv';
const CSV_CITY = 'generic_city_202605291856.csv';
const CSV_PINCODE = 'generic_pincode_202605291858.csv';

/** CSV `state_id` → `state.name` in our DB (must match state.seed / INDIAN_STATES). */
const CSV_STATE_NAME_TO_DB = {
  'Jammu & Kashmir': 'Jammu and Kashmir',
  'Andaman and Nicobar Islands': 'Andaman and Nicobar',
  'Daman and Diu': 'Daman and Diu',
  'Dadra and Nagar Haveli': 'Dadra and Nagar Haveli',
};

const SKIP_CSV_STATE_NAMES = new Set(['Other Territory']);

function parseArgs(argv) {
  const out = { csvDir: null, sqlOnly: false, execute: false, outDir: join(ROOT, 'prisma/data/geography/generated') };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--sql-only') out.sqlOnly = true;
    else if (a === '--execute') out.execute = true;
    else if (a === '--csv-dir' && argv[i + 1]) out.csvDir = resolve(argv[++i]);
    else if (a === '--out-dir' && argv[i + 1]) out.outDir = resolve(argv[++i]);
  }
  if (!out.sqlOnly && !out.execute) out.sqlOnly = true;
  return out;
}

function sqlEscape(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "''");
}

async function readCsvRows(filePath) {
  const rows = [];
  const rl = createInterface({ input: createReadStream(filePath), crlfDelay: Infinity });
  let headers = null;
  for await (const line of rl) {
    if (!line.trim()) continue;
    const parts = [];
    let cur = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (ch === '"') {
        inQuotes = !inQuotes;
        continue;
      }
      if (ch === ',' && !inQuotes) {
        parts.push(cur);
        cur = '';
        continue;
      }
      cur += ch;
    }
    parts.push(cur);
    if (!headers) {
      headers = parts.map((h) => h.trim());
      continue;
    }
    const row = {};
    headers.forEach((h, idx) => {
      row[h] = (parts[idx] ?? '').trim();
    });
    rows.push(row);
  }
  return rows;
}

function mapCsvStateName(csvName) {
  return CSV_STATE_NAME_TO_DB[csvName] ?? csvName;
}

function normalizeCityName(name) {
  return name.replace(/\s+/g, ' ').trim().toUpperCase();
}

async function loadCsvBundle(csvDir) {
  const [stateRows, cityRows, pincodeRows] = await Promise.all([
    readCsvRows(join(csvDir, CSV_STATE)),
    readCsvRows(join(csvDir, CSV_CITY)),
    readCsvRows(join(csvDir, CSV_PINCODE)),
  ]);

  const csvStateIdToName = new Map();
  for (const row of stateRows) {
    csvStateIdToName.set(Number(row.state_id), row.state_name);
  }

  const cities = [];
  let sourceId = 0;
  for (const row of cityRows) {
    sourceId += 1;
    const csvStateId = Number(row.city_state_id);
    const csvStateName = csvStateIdToName.get(csvStateId);
    if (!csvStateName || SKIP_CSV_STATE_NAMES.has(csvStateName)) continue;
    cities.push({
      sourceCityId: sourceId,
      name: normalizeCityName(row.city_name),
      dbStateName: mapCsvStateName(csvStateName),
    });
  }

  const pincodeByCode = new Map();
  for (const row of pincodeRows) {
    const code = row.pincode_code.trim();
    if (!/^\d{6}$/.test(code)) continue;
    const sourceCityId = Number(row.pincode_city_id);
    if (!Number.isFinite(sourceCityId)) continue;
    if (!pincodeByCode.has(code)) {
      pincodeByCode.set(code, sourceCityId);
    }
  }

  return { cities, pincodeByCode, cityCount: cities.length, pincodeCount: pincodeByCode.size };
}

function buildSql({ cities, pincodeByCode }) {
  const lines = [];
  lines.push('-- Generated by scripts/import-geography-bulk.mjs');
  lines.push('SET NAMES utf8mb4;');
  lines.push('SET FOREIGN_KEY_CHECKS = 0;');
  lines.push('START TRANSACTION;');
  lines.push('');
  lines.push('-- Normalize existing city names to uppercase for consistent lookups');
  lines.push('UPDATE city SET name = UPPER(name);');
  lines.push('');

  const CHUNK = 200;
  for (let i = 0; i < cities.length; i += CHUNK) {
    const chunk = cities.slice(i, i + CHUNK);
    const values = chunk
      .map(
        (c) =>
          `(${c.sourceCityId}, '${sqlEscape(c.name)}', (SELECT id FROM state WHERE name = '${sqlEscape(c.dbStateName)}' LIMIT 1))`,
      )
      .join(',\n  ');
    lines.push(
      'INSERT INTO city (source_city_id, name, state_id, is_active)',
      'VALUES',
      `  ${values}`,
      'ON DUPLICATE KEY UPDATE',
      '  name = VALUES(name),',
      '  state_id = VALUES(state_id),',
      '  source_city_id = VALUES(source_city_id),',
      '  is_active = TRUE;',
    );
    lines.push('');
  }

  const pinEntries = [...pincodeByCode.entries()];
  for (let i = 0; i < pinEntries.length; i += CHUNK) {
    const chunk = pinEntries.slice(i, i + CHUNK);
    const values = chunk
      .map(
        ([code, sourceCityId]) =>
          `('${sqlEscape(code)}', (SELECT id FROM city WHERE source_city_id = ${sourceCityId} LIMIT 1))`,
      )
      .join(',\n  ');
    lines.push(
      'INSERT INTO pincode (code, city_id, is_active)',
      'VALUES',
      `  ${values}`,
      'ON DUPLICATE KEY UPDATE',
      '  city_id = VALUES(city_id),',
      '  is_active = TRUE;',
    );
    lines.push('');
  }

  lines.push('COMMIT;');
  lines.push('SET FOREIGN_KEY_CHECKS = 1;');
  return lines.join('\n');
}

function runMysqlCli(sqlPath) {
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error('DATABASE_URL is required for --execute');
  }
  const parsed = new URL(url);
  const host = parsed.hostname;
  const port = parsed.port || '3306';
  const user = decodeURIComponent(parsed.username);
  const password = decodeURIComponent(parsed.password);
  const database = parsed.pathname.replace(/^\//, '');

  const args = [
    '-h',
    host,
    '-P',
    port,
    '-u',
    user,
    `--database=${database}`,
    '-e',
    `source ${sqlPath.replace(/\\/g, '/')}`,
  ];
  const env = { ...process.env };
  if (password) env.MYSQL_PWD = password;

  const result = spawnSync('mysql', args, { env, stdio: 'inherit' });
  if (result.status !== 0) {
    throw new Error(`mysql CLI failed (exit ${result.status ?? 'unknown'})`);
  }
}

async function main() {
  const args = parseArgs(process.argv);
  if (!args.csvDir) {
    console.error(
      'Missing --csv-dir. Example:\n  node scripts/import-geography-bulk.mjs --csv-dir "/home/user/Documents/city data"',
    );
    process.exit(1);
  }

  console.log(`Loading CSVs from ${args.csvDir} ...`);
  const bundle = await loadCsvBundle(args.csvDir);
  console.log(`Cities to import: ${bundle.cityCount}`);
  console.log(`Unique pincodes: ${bundle.pincodeCount}`);

  const sql = buildSql(bundle);
  mkdirSync(args.outDir, { recursive: true });
  const sqlPath = join(args.outDir, 'import_geography.sql');
  writeFileSync(sqlPath, sql, 'utf8');
  console.log(`Wrote ${sqlPath} (${(sql.length / 1024).toFixed(1)} KB)`);

  if (args.execute) {
    console.log('Executing via mysql CLI...');
    runMysqlCli(sqlPath);
    console.log('Import complete.');
  } else {
    console.log('\nProd: deploy migration, then run:');
    console.log(`  mysql ... < ${sqlPath}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
